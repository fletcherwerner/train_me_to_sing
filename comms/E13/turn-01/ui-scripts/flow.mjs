import { chromium } from '@playwright/test';
import { appUrl } from '../../../../harness/lib/app-url.mjs';
const out = new URL('../screenshots/', import.meta.url).pathname;
const seed = JSON.stringify({version:1,range:{lowMidi:45,highMidi:64,assessedAt:new Date().toISOString()},settings:{latencyOffsetMs:0},progress:{},importedLessons:[]});
const b = await chromium.launch();
const ctx = await b.newContext({ ignoreHTTPSErrors: true, viewport:{width:393,height:852}, deviceScaleFactor:2 });
await ctx.addInitScript(v=>{ if(!localStorage.getItem('tmts.v1')) localStorage.setItem('tmts.v1',v)}, seed);
const page = await ctx.newPage();
const sizes = {laptop:{width:1280,height:800},phone:{width:393,height:852}};
const shot = async (n)=>{ for (const [k,v] of Object.entries(sizes)) { await page.setViewportSize(v); await page.waitForTimeout(250); await page.screenshot({path:`${out}${n}-${k}.png`}); } };
const btn=(n)=>page.getByRole('button',{name:n,exact:true});
const base = appUrl();
await page.goto(base+'/#/lesson/s1-05?sim=perfect');
await page.waitForTimeout(500);
await shot('l-intro');
await btn('Start').click();
await shot('l-ido-idle');
await btn('Play').click();
await page.waitForTimeout(6000);
await shot('l-ido-run');
await btn('Repeat').waitFor({timeout:120000});
await btn('Next').click();
await shot('l-wedo-idle');
await btn('Sing along').click(); await page.waitForTimeout(4000);
await shot('l-wedo-run');
// mic lost
await page.evaluate(()=>window.__tmtsTest.loseMic()); await page.waitForTimeout(1500);
await shot('l-miclost');
await btn('Reconnect microphone').click(); await page.waitForTimeout(500);
await btn('Sing along').click();
await page.locator('[data-testid=practice-line]').waitFor({timeout:60000});
await shot('l-wedo-done');
await btn('Next').click();
await btn('Start').click(); await page.waitForTimeout(5000);
await shot('l-youdo-run');
await page.evaluate(()=>window.__tmtsTest.suspendAudio()); await page.waitForTimeout(2500);
await shot('l-stalled');
await btn('Try again').click(); await page.waitForTimeout(500);
await btn('Start').click();
await page.locator('[data-testid=results]').waitFor({timeout:90000});
await shot('l-results');
await page.goto(base+'/#/lesson/s3-04?sim=flat40'); await page.waitForTimeout(500);
await btn('Start').click(); await btn('Play').click();
await btn('Repeat').waitFor({timeout:150000}); await btn('Next').click(); await btn('Next').click().catch(()=>{});
await shot('l-s304-youdo-idle');
await btn('Start').click().catch(()=>{}); await page.waitForTimeout(5000);
await shot('l-s304-youdo-run');
await b.close();
