import { chromium } from '@playwright/test';
import { appUrl } from '../../../../harness/lib/app-url.mjs';
const out = 'comms/S01/turn-01/screenshots/';
const sizes = { laptop: { width: 1280, height: 800 }, phone: { width: 393, height: 852 } };
const SEED = `if(!localStorage.getItem('tmts.v1'))localStorage.setItem('tmts.v1',JSON.stringify({version:1,range:{lowMidi:45,highMidi:64,assessedAt:new Date().toISOString()},settings:{latencyOffsetMs:0},progress:{},importedLessons:[]}))`;
const b = await chromium.launch();
const base = appUrl();
for (const [n, vp] of Object.entries(sizes)) {
  const ctx = await b.newContext({ viewport: vp, ignoreHTTPSErrors: true, isMobile: n === 'phone', hasTouch: n === 'phone' });
  await ctx.addInitScript(SEED);
  const p = await ctx.newPage();
  await p.goto(base + '/#/settings'); await p.waitForTimeout(1000);
  await p.screenshot({ path: out + `settings-noprofile-${n}.png`, fullPage: true });
  const nm = n === 'laptop' ? 'Zed Laptop' : 'Zed Phone';
  await p.getByTestId('profile-name').fill(nm);
  await p.screenshot({ path: out + `settings-filled-${n}.png`, fullPage: true });
  await p.getByTestId('profile-create').click(); await p.waitForTimeout(800);
  await p.screenshot({ path: out + `after-create-fresh-${n}.png`, fullPage: true });
  console.log(n, p.url());
  await p.goto(base + '/#/'); await p.waitForTimeout(800);
  await p.screenshot({ path: out + `home-profile-${n}.png`, fullPage: true });
  await p.goto(base + '/#/settings'); await p.waitForTimeout(800);
  await p.screenshot({ path: out + `settings-active-${n}.png`, fullPage: true });
  await p.getByTestId('profile-name').fill(nm);
  await p.getByTestId('profile-create').click(); await p.waitForTimeout(800);
  await p.screenshot({ path: out + `duplicate-${n}.png`, fullPage: true });
  await p.getByTestId('profile-name').fill('');
  await p.getByTestId('profile-create').click(); await p.waitForTimeout(500);
  await p.screenshot({ path: out + `emptyname-${n}.png`, fullPage: true });
  const bt = await p.evaluate(() => [...document.querySelectorAll('button,input')].map(e => { const r = e.getBoundingClientRect(); return [e.tagName, (e.textContent || '').trim().slice(0, 20) || e.type, Math.round(r.width), Math.round(r.height)]; }));
  console.log(n, JSON.stringify(bt), await p.evaluate(() => document.documentElement.scrollWidth));
  await ctx.close();
}
const ctx = await b.newContext({ viewport: sizes.phone, ignoreHTTPSErrors: true, colorScheme: 'dark' });
await ctx.addInitScript(SEED);
const p = await ctx.newPage();
await p.goto(base + '/#/settings'); await p.waitForTimeout(1000);
await p.screenshot({ path: out + 'settings-dark-phone.png', fullPage: true });
await p.goto(base + '/#/'); await p.waitForTimeout(500);
await p.screenshot({ path: out + 'home-dark-phone.png', fullPage: true });
await b.close();
