import { chromium } from 'playwright';
import { appUrl } from '../../../../harness/lib/app-url.mjs';
const out = new URL('../screenshots/', import.meta.url).pathname;
const seed = { version: 1, range: { lowMidi: 45, highMidi: 64, assessedAt: '2025-01-01T00:00:00.000Z' }, settings: { latencyOffsetMs: 0 }, progress: {}, importedLessons: [] };
const sizes = { laptop: { width: 1280, height: 800 }, phone: { width: 393, height: 852 } };
const sim = process.argv[2] || 'perfect';
for (const [name, vp] of Object.entries(sizes)) {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: vp, ignoreHTTPSErrors: true, hasTouch: name === 'phone' });
  await ctx.addInitScript((s) => localStorage.setItem('tmts.v1', JSON.stringify(s)), seed);
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push(e.message));
  const shot = async (n) => {
    await page.screenshot({ path: `${out}${sim}-${name}-${n}.png`, fullPage: true });
    const o = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth, sh: document.documentElement.scrollHeight, ch: innerHeight }));
    console.log(sim, name, n, JSON.stringify(o));
  };
  await page.goto(appUrl() + `/#/lesson/demo?sim=${sim}`);
  await page.waitForTimeout(800);
  await shot('1-intro');
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.waitForTimeout(500);
  await shot('2-ido-idle');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForTimeout(2000);
  await shot('3-ido-leadin');
  await page.waitForTimeout(7000);
  await shot('4-ido-running');
  await page.getByRole('button', { name: 'Repeat' }).waitFor({ timeout: 30000 });
  await shot('5-ido-done');
  await page.getByRole('button', { name: 'Next' }).click();
  await page.waitForTimeout(300);
  await shot('6-wedo-idle');
  await page.getByRole('button', { name: 'Sing along' }).click();
  await page.waitForTimeout(9000);
  await shot('7-wedo-running');
  await page.getByTestId('practice-line').waitFor({ timeout: 30000 });
  await shot('8-wedo-done');
  await page.getByRole('button', { name: 'Next' }).click();
  await page.waitForTimeout(300);
  await shot('9-youdo-idle');
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.waitForTimeout(9000);
  await shot('10-youdo-running');
  await page.getByTestId('results-verdict').waitFor({ timeout: 40000 });
  await page.waitForTimeout(300);
  await shot('11-results');
  console.log('errs', errs);
  await b.close();
}
